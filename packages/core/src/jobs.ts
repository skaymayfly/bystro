export interface JobDefinition<TData> {
  /** Unique across all queues, e.g. `maintenance.cleanup-oauth-requests`. */
  name: string;
  queue: ProcessedQueueName;
  /** Payloads are validated when enqueued and again when processed. */
  schema: z.ZodType<TData>;
  retry: RetryPolicy;
}

export function defineJob<TData>(definition: JobDefinition<TData>): JobDefinition<TData> {
  return definition;
}

const emptyPayloadSchema = z.strictObject({});
/** Payload of jobs that need no input. */
export type EmptyPayload = z.infer<typeof emptyPayloadSchema>;

