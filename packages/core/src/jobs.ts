/** What is kept about a job that failed for good. No error text: it may quote external data. */
export const deadLetterSchema = z.strictObject({
  queue: z.string(),
  name: z.string(),
  jobId: z.string(),
  data: z.unknown(),
  attemptsMade: z.number().int().nonnegative(),
  errorCode: z.string(),
  failedAt: z.iso.datetime(),
});

export type DeadLetter = z.infer<typeof deadLetterSchema>;

const ERROR_CODE = /^[A-Za-z][A-Za-z0-9_.-]{0,63}$/;

/**
 * Short machine code of an error for logs and dead letters: its `code` if it has a tidy one,
 * otherwise the class name. Never the message, which may contain external or sensitive text.
 */
export function jobErrorCode(error: unknown): string {
  if (typeof error === "object" && error !== null) {
    const { code, name } = error as { code?: unknown; name?: unknown };
    if (typeof code === "string" && ERROR_CODE.test(code)) {
      return code;
    }
    if (typeof name === "string" && ERROR_CODE.test(name)) {
      return name;
    }
  }
  return "unknown_error";
}
