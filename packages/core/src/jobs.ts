/** Planning happens in Czech local time (morning brief at 7:00, nightly maintenance). */
export const SCHEDULE_TIME_ZONE = "Europe/Prague";

export interface JobSchedule {
  /** Stable id; registering the same id again updates the schedule instead of adding one. */
  id: string;
  /** Cron expression evaluated in {@link SCHEDULE_TIME_ZONE}. */
  pattern: string;
  /** Name of the job to run; its payload is `data`. */
  jobName: string;
  retry: RetryPolicy;
  data: Record<string, unknown>;
}

function schedule<TData extends Record<string, unknown>>(
  id: string,
  pattern: string,
  job: JobDefinition<TData>,
  data: TData,
): JobSchedule {
  return { id, pattern, jobName: job.name, retry: job.retry, data: job.schema.parse(data) };
}

/**
 * How often invoices are fetched. Providers limit requests (a Fakturoid account has a
 * monthly allowance, 1 500 on the plan seen on 2026-10-11), and an incremental run costs
 * one request when nothing changed: hourly during the working day is about 450 a month.
 * The weekly full run also finds invoices deleted at the source.
 */
export const JOB_SCHEDULES: readonly JobSchedule[] = [
  schedule("cleanup-oauth-requests", "30 3 * * *", cleanupOAuthRequestsJob, {}),
  schedule("sync-invoices-hourly", "0 6-20 * * *", dispatchInvoiceSyncJob, { mode: "incremental" }),
  schedule("sync-invoices-weekly", "30 2 * * 0", dispatchInvoiceSyncJob, { mode: "full" }),
  // Mail: an incremental run costs a few quota units when nothing changed (Gmail allows
  // 6 000 a minute per user), so every 5 minutes by day and hourly at night. The nightly
  // full run puts the labels right if a change was missed and drops what left the window.
  schedule("sync-mail-day", "*/5 6-21 * * *", dispatchMailSyncJob, { mode: "incremental" }),
  schedule("sync-mail-night", "0 0-5,22,23 * * *", dispatchMailSyncJob, { mode: "incremental" }),
  schedule("sync-mail-daily-full", "15 3 * * *", dispatchMailSyncJob, { mode: "full" }),
];

// ---------------------------------------------------------------------------------------
// Rate limits
// ---------------------------------------------------------------------------------------

/** At most `max` calls per `windowMs` for one key (a provider, or a provider and connection). */
export interface RateLimit {
  max: number;
  windowMs: number;
}

export interface RateLimitDecision {
  allowed: boolean;
  /** How long to wait before trying again; 0 when allowed. */
  retryAfterMs: number;
}

/**
 * Decides from the counter of the current window. `count` already includes this call and
 * `windowRemainingMs` is the time until the counter resets.
 */
export function decideRateLimit(
  limit: RateLimit,
  count: number,
  windowRemainingMs: number,
): RateLimitDecision {
  if (count <= limit.max) {
    return { allowed: true, retryAfterMs: 0 };
  }
  const remaining = windowRemainingMs > 0 ? windowRemainingMs : limit.windowMs;
  return { allowed: false, retryAfterMs: Math.min(remaining, limit.windowMs) };
}

/** Counter key of a rate limit, e.g. `fio.<connectionId>`. */
export function rateLimitKey(provider: string, scope?: string): string {
  return scope === undefined ? buildJobId(provider) : buildJobId(provider, scope);
}

