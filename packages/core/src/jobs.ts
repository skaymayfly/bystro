// ---------------------------------------------------------------------------------------
// Rate limits
// ---------------------------------------------------------------------------------------

/** At most `max` calls per `windowMs` for one key (a provider, or a provider and connection). */
export interface RateLimit {
  max: number;
  windowMs: number;
}

export interface RateLimitDecision {
  allowed: boolean;
  /** How long to wait before trying again; 0 when allowed. */
  retryAfterMs: number;
}

/**
 * Decides from the counter of the current window. `count` already includes this call and
 * `windowRemainingMs` is the time until the counter resets.
 */
export function decideRateLimit(
  limit: RateLimit,
  count: number,
  windowRemainingMs: number,
): RateLimitDecision {
  if (count <= limit.max) {
    return { allowed: true, retryAfterMs: 0 };
  }
  const remaining = windowRemainingMs > 0 ? windowRemainingMs : limit.windowMs;
  return { allowed: false, retryAfterMs: Math.min(remaining, limit.windowMs) };
}

/** Counter key of a rate limit, e.g. `fio.<connectionId>`. */
export function rateLimitKey(provider: string, scope?: string): string {
  return scope === undefined ? buildJobId(provider) : buildJobId(provider, scope);
}

